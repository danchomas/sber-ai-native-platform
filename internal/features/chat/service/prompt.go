// quotedPhrase — фраза в «ёлочках»: готовая формулировка, которую модель
// должна произнести дословно («последний период неполный, в сравнение его
// не беру»), или пример вопроса пользователя. Её повтор в ответе — не утечка
// инструкций, поэтому в поиск пересказа она не входит.
var quotedPhrase = regexp.MustCompile(`«[^»]*»`)

func echoSources(prompts ...string) []string {
	out := make([]string, len(prompts))
	for i, p := range prompts {
		out[i] = quotedPhrase.ReplaceAllString(instructionText(p), " ")
	}
	return out
}

