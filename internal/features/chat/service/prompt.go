func buildPlannerPrompt(schemaContext string, allowSQL bool) string {
	if allowSQL {
		return fmt.Sprintf(plannerSystemPrompt, strings.TrimSpace(schemaContext))
	}
	return fmt.Sprintf(queryPlannerSystemPrompt, strings.TrimSpace(schemaContext),
		joinValues(analytics.Funcs), joinValues(analytics.Grains), joinValues(analytics.Ops))
}

func joinValues[T ~string](values []T) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = string(v)
	}
	return strings.Join(parts, "|")
}

func buildRepairPrompt(schemaContext, question, badSQL, reason string) string {
	var sb strings.Builder
	sb.WriteString("ОПИСАНИЕ ДАННЫХ:\n")
	sb.WriteString(strings.TrimSpace(schemaContext))
	sb.WriteString("\n\nВОПРОС ПОЛЬЗОВАТЕЛЯ: ")
	sb.WriteString(question)
	sb.WriteString("\n\nЗАПРОС С ОШИБКОЙ:\n")
	sb.WriteString(badSQL)
	sb.WriteString("\n\nПРИЧИНА ОТКАЗА: ")
	sb.WriteString(reason)
	sb.WriteString("\n\nИсправь запрос.")
	return sb.String()
}

func buildNarrationPrompt(question, title string, resultDigest string, warnings []string) string {
	var sb strings.Builder
	sb.WriteString("ВОПРОС: ")
	sb.WriteString(question)
	if title != "" {
		sb.WriteString("\nЗАГОЛОВОК РЕЗУЛЬТАТА: ")
		sb.WriteString(title)
	}
	sb.WriteString("\n\nРЕЗУЛЬТАТ ЗАПРОСА:\n")
	sb.WriteString(resultDigest)
	if len(warnings) > 0 {
		sb.WriteString("\nОГОВОРКИ: ")
		sb.WriteString(strings.Join(warnings, "; "))
	}
	sb.WriteString("\n\nИзложи результат для бизнес-пользователя.")
	return sb.String()
}
